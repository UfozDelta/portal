"""Build the compose override that portal layers on top of the project's own
compose file. The project's compose file is never mutated.
"""

from __future__ import annotations

from pathlib import Path

import yaml

from ..detect import ProjectPlan


def build_override(plan: ProjectPlan) -> dict:
    """Override doc: deterministic container name, portal network, labels, and
    no host port publication.

    `ports: []` replaces the project's own list — compose merges mappings but
    replaces sequences at the service level for `ports`, so an empty list is
    what actually strips host publication.

    `networks` is replaced the same way, so portal's network is appended to the
    ones the service already had rather than substituted for them — otherwise a
    service would lose its link to the rest of its own stack.
    """
    networks = [n for n in plan.service_networks if n != "portal"]
    networks.append("portal")

    return {
        "services": {
            plan.service: {
                "container_name": plan.container_name,
                "ports": [],
                "expose": [str(plan.port)],
                "networks": networks,
                "restart": "unless-stopped",
                "labels": {
                    "portal.managed": "true",
                    "portal.project": plan.slug,
                    "portal.service": plan.service,
                    "portal.hostname": plan.fqdn or "",
                    "portal.port": str(plan.port),
                },
            }
        },
        "networks": {
            "portal": {
                "name": plan.network,
                "external": True,
            }
        },
    }


def synthesize_compose(plan: ProjectPlan) -> dict:
    """A minimal compose file for a Dockerfile-only project.

    Lives under portal's state dir, never in the target project. env_file is
    only wired up when the project actually has a .env — portal does not read
    its contents, it just hands the path to compose.
    """
    service: dict = {
        "build": {"context": str(plan.source_path)},
    }
    if (plan.source_path / ".env").is_file():
        service["env_file"] = [str(plan.source_path / ".env")]
    return {"services": {plan.service: service}}


def write_yaml(data: dict, path: Path) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        "# generated by portal - do not edit, it is rewritten on every deploy\n"
        + yaml.safe_dump(data, sort_keys=False),
        encoding="utf-8",
    )
    return path
